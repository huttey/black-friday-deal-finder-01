export function discountOf(deal) {
  if (deal.usual === null || deal.usual <= deal.sale) return null;
  return Math.round((1 - deal.sale / deal.usual) * 100);
}

export function savingOf(deal) {
  if (deal.usual === null || deal.usual <= deal.sale) return 0;
  return deal.usual - deal.sale;
}

export function money(n) {
  return '$' + n.toFixed(2).replace(/\.00$/, '');
}
